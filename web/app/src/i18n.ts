const lang = (navigator.languages?.[0] ?? navigator.language ?? "en").toLowerCase().startsWith("de") ? "de" : "en";

export const locale = lang === "de" ? "de-DE" : "en-GB";

/** The text in the browser's language, with `{name}` replaced by `values.name`. */
export function t(text: string, values: Record<string, string | number> = {}): string {
  const translated = lang === "de" ? (de[text] ?? text) : text;
  return translated.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}

export function setDocumentLanguage(): void {
  document.documentElement.lang = lang;
}
